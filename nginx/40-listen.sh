#!/bin/sh
# shellcheck shell=busybox  # the nginx alpine image: busybox ash (pipefail is supported)
# 40-listen.sh - where nginx listens: port 8080 on IPv4, and on IPv6 too when the pod has IPv6.
#
# A dual-stack cluster gives the pod an IPv6 address as well, and the Service, Traefik or another pod
# may connect over it: `listen 8080;` alone accepts IPv4 only, and an IPv6 connection is refused.
# `listen [::]:8080;` makes nginx refuse to start where the kernel has no IPv6 (net.ipv6 disabled in
# the pod), so it is added only when /proc/net/if_inet6 exists - the same test as the image's own
# 10-listen-on-ipv6-by-default.sh, which edits default.conf and cannot run on a read-only root.
#
# Run by the nginx image's /docker-entrypoint.sh before nginx starts, on every container start.
# Writes /tmp/nginx-listen.conf (the root filesystem is read-only in the cluster; /tmp is an emptyDir),
# which default.conf includes in its server block.
set -euo pipefail

port="8080"

{
  echo "# Generated by /docker-entrypoint.d/40-listen.sh"
  echo "listen ${port};"
  if [ -e /proc/net/if_inet6 ]; then
    echo "listen [::]:${port};"
  fi
} > /tmp/nginx-listen.conf

if [ -e /proc/net/if_inet6 ]; then
  echo "40-listen.sh: listening on ${port}, IPv4 and IPv6"
else
  echo "40-listen.sh: listening on ${port}, IPv4 only (no IPv6 in this kernel or pod)"
fi
