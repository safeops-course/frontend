#!/bin/sh
# shellcheck shell=busybox  # the nginx alpine image: busybox ash (pipefail is supported)
# 45-backend-upstream.sh - where /api/ goes, resolved per request instead of once at start.
#
# `proxy_pass http://backend:80` makes nginx look the name up once, when it starts: if it does not
# resolve at that moment - the backend Service not created yet, DNS blocked by a NetworkPolicy - nginx
# stops with "[emerg] host not found in upstream" and the pod crash-loops (seen on GKE, 2026-10-15).
# With a variable in proxy_pass nginx resolves the name at request time through `resolver`: it starts
# without a backend, /api/ answers 502 until the backend is there, and it follows a changed address.
#
# nginx's resolver knows no search domains, so the name must be complete. Both come from the pod's own
# /etc/resolv.conf, nothing is configured per cluster or environment:
#   resolver   its nameserver lines (kube-dns, or the node-local DNS cache answering on its address);
#   upstream   "backend" + "." + its first search domain - in Kubernetes "<namespace>.svc.<cluster
#              domain>", so backend.develop.svc.cluster.local:80. Without a search domain (docker run,
#              compose) the bare name stays, which Docker's DNS resolves.
#
# The name and port are fixed on purpose, not read from BACKEND_HOST / BACKEND_PORT: Kubernetes puts
# service links into every pod started after a Service named "backend" exists - BACKEND_PORT=
# "tcp://10.96.2.210:80", BACKEND_SERVICE_HOST, ... - so such a variable would hold the cluster's value,
# not ours (a start refused on it crash-looped every frontend pod; found on kind, 2026-10-15).
#
# Run by the nginx image's /docker-entrypoint.sh before nginx starts, on every container start.
# Writes /tmp/nginx-backend.conf (the root filesystem is read-only in the cluster; /tmp is an emptyDir),
# which nginx.conf includes in its http block. Exits non-zero without a nameserver, and the entrypoint
# then stops the container: nginx could not reach the backend at all.
set -euo pipefail

host="backend"
port="80"

# All nameservers, space-separated; an IPv6 address needs brackets in nginx's resolver.
nameservers="$(awk '$1 == "nameserver" { a = $2; if (index(a, ":")) a = "[" a "]"; printf "%s ", a }' /etc/resolv.conf)"
if [ -z "${nameservers}" ]; then
  echo "45-backend-upstream.sh: no nameserver in /etc/resolv.conf - nginx could not resolve ${host}" >&2
  exit 1
fi

# The first search domain, only one of Kubernetes' form "<namespace>.svc.<cluster domain>": Docker copies
# the host's search domains (a home or office domain), and backend.<that> would resolve nowhere.
domain="$(awk '$1 == "search" { print $2; exit }' /etc/resolv.conf)"
case "${domain}" in
  *.svc.*) ;;
  *) domain="" ;;
esac
upstream="${host}${domain:+.${domain}}"

{
  echo "# Generated by /docker-entrypoint.d/45-backend-upstream.sh from /etc/resolv.conf"
  echo "resolver ${nameservers}valid=10s;"
  echo "resolver_timeout 5s;"
  echo "map \"\" \$backend_upstream {"
  echo "    default \"${upstream}:${port}\";"
  echo "}"
} > /tmp/nginx-backend.conf

echo "45-backend-upstream.sh: /api/ -> ${upstream}:${port}, resolved per request"
