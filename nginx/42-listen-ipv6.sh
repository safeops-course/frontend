#!/bin/sh
# shellcheck shell=busybox  # the nginx alpine image: busybox ash (pipefail is supported)
# 42-listen-ipv6.sh - nginx listens on IPv6 too when the pod has it (dual-stack); IPv4 always.
#
# A dual-stack cluster gives the pod an IPv6 address as well, and the Service, Traefik or another pod
# may connect over it: `listen 8080;` (default.conf) accepts IPv4 only. `listen [::]:8080;` makes nginx
# refuse to start where the kernel has no IPv6 (booted with ipv6.disable=1), so it is added only when
# /proc/net/if_inet6 exists - the same test as the image's own 10-listen-on-ipv6-by-default.sh, which
# edits default.conf and cannot run on a read-only root.
#
# Run by the nginx image's /docker-entrypoint.sh before nginx starts, on every container start.
# Writes /tmp/nginx-listen-ipv6.conf only when the pod has IPv6 (the root filesystem is read-only in the
# cluster; /tmp is an emptyDir). default.conf includes /tmp/nginx-listen-ipv6*.conf - a glob, so without
# the file (no IPv6, or this script did not run) nginx still starts and listens on IPv4.
set -euo pipefail

port="8080"
conf="/tmp/nginx-listen-ipv6.conf"

if [ -e /proc/net/if_inet6 ]; then
  printf '# Generated by /docker-entrypoint.d/42-listen-ipv6.sh\nlisten [::]:%s;\n' "${port}" > "${conf}"
  echo "42-listen-ipv6.sh: listening on ${port}, IPv4 and IPv6"
else
  rm -f "${conf}"
  echo "42-listen-ipv6.sh: listening on ${port}, IPv4 only (no IPv6 in this kernel)"
fi
